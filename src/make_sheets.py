"""
Generate blinded labelling sheets, and lock them when done.

Enforces the protocol in ANNOTATION_GUIDELINE.md §5:
  P1  no IV columns ever reach the annotator's screen
  P2  L0 must be complete and locked before L1 can be generated
  P3  each pass gets its own random order, seed recorded
  P5  test-retest subset drawn automatically

Usage:
  python src/make_sheets.py l0      <comments.csv>   # first pass
  python src/make_sheets.py lock    label_L0.csv     # freeze + hash
  python src/make_sheets.py l1      <comments.csv>   # needs L0 locked
  python src/make_sheets.py retest  label_L0.csv     # 10% blind re-label
  python src/make_sheets.py agree   a.csv b.csv      # kappa / alpha
"""
import sys
import json
import hashlib
from pathlib import Path
from datetime import datetime, timezone
import pandas as pd
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
LAB = ROOT / 'labels'
LAB.mkdir(exist_ok=True)
LOCKFILE = LAB / 'locks.json'

# Columns the annotator may never see during labelling (P1).
FORBIDDEN = {'cmi', 'switch_points', 'matrix_lang', 'n_hi', 'n_en',
             'swear_freq', 'swear_count', 'swear_max_severity',
             'swear_mean_severity', 'direction_score', 'profanity_valence',
             'swear_tokens', 'label', 'y', 'pred'}


def _locks():
    return json.loads(LOCKFILE.read_text()) if LOCKFILE.exists() else {}


def _save_locks(d):
    LOCKFILE.write_text(json.dumps(d, indent=2))


def sha256(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def uid_for(text: str, salt: str = 'cmi2026') -> str:
    """Opaque id. Carries no thread or position information (P1/P2)."""
    return hashlib.sha1((salt + str(text)).encode()).hexdigest()[:12]


def _require_text(df):
    if 'text' not in df.columns:
        sys.exit("input csv must have a 'text' column")
    leaked = FORBIDDEN & set(df.columns)
    return df, leaked


def make_l0(src, seed=20261106):
    df, leaked = _require_text(pd.read_csv(src))
    out = pd.DataFrame({'uid': [uid_for(t) for t in df.text],
                        'text': df.text})
    out = out.drop_duplicates('uid')
    out = out.sample(frac=1.0, random_state=seed).reset_index(drop=True)
    out['label'] = ''
    out['note'] = ''
    path = LAB / 'label_L0.csv'
    if path.exists():
        sys.exit(f'{path} already exists — refusing to overwrite. '
                 'Lock it or move it aside.')
    out.to_csv(path, index=False, encoding='utf-8-sig')
    print(f'wrote {path}  rows={len(out)}  seed={seed}')
    if leaked:
        print(f'  stripped IV columns (P1): {sorted(leaked)}')
    print('\nLabel every row 3 / 2 / 1 / 0 / X before running "lock".')
    print('Do NOT compute or look at any IV until then.')


def lock(path):
    p = Path(path)
    df = pd.read_csv(p)
    blank = df.label.isna().sum() + (df.label.astype(str).str.strip() == '').sum()
    if blank:
        sys.exit(f'{blank} rows still unlabelled — cannot lock.')
    bad = set(df.label.astype(str).str.strip().str.upper()) - {'3', '2', '1', '0', 'X'}
    if bad:
        sys.exit(f'invalid labels present: {sorted(bad)}')
    locks = _locks()
    locks[p.name] = {'sha256': sha256(p), 'rows': len(df),
                     'locked_at': datetime.now(timezone.utc).isoformat(),
                     'dist': df.label.astype(str).str.upper()
                               .value_counts().to_dict()}
    _save_locks(locks)
    print(f'LOCKED {p.name}')
    print(f'  sha256 {locks[p.name]["sha256"]}')
    print(f'  distribution {locks[p.name]["dist"]}')
    print('\nDo not edit this file again. Corrections go in a separate file.')


def make_l1(src, seed=20261108):
    locks = _locks()
    if 'label_L0.csv' not in locks:
        sys.exit('L0 is not locked. Finish and lock the comment-only pass '
                 'first (protocol P2) — you cannot un-see context.')
    p0 = LAB / 'label_L0.csv'
    if p0.exists() and sha256(p0) != locks['label_L0.csv']['sha256']:
        sys.exit('label_L0.csv has changed since it was locked. '
                 'Restore it or re-lock deliberately.')
    df, leaked = _require_text(pd.read_csv(src))
    if 'parent_text' not in df.columns:
        sys.exit("L1 needs a 'parent_text' column (the context condition)")
    out = pd.DataFrame({'uid': [uid_for(t) for t in df.text],
                        'parent_text': df.parent_text.fillna('[top-level]'),
                        'text': df.text})
    out = out.drop_duplicates('uid')
    out = out.sample(frac=1.0, random_state=seed).reset_index(drop=True)
    out['label'] = ''
    out['note'] = ''
    path = LAB / 'label_L1.csv'
    if path.exists():
        sys.exit(f'{path} already exists — refusing to overwrite.')
    out.to_csv(path, index=False, encoding='utf-8-sig')
    print(f'wrote {path}  rows={len(out)}  seed={seed} (fresh order, P3)')
    print('Confirm at least 48h have passed since L0 (P4).')


def make_retest(path, frac=0.10, seed=99):
    df = pd.read_csv(path)
    s = df.sample(frac=frac, random_state=seed)
    out = s[['uid', 'text']].sample(frac=1.0, random_state=seed + 1)
    out = out.reset_index(drop=True)
    out['label'] = ''
    out['note'] = ''
    p = LAB / 'label_L0_retest.csv'
    out.to_csv(p, index=False, encoding='utf-8-sig')
    print(f'wrote {p}  rows={len(out)}  ({frac:.0%} of {len(df)})')
    print('Label blind, then: python src/make_sheets.py agree '
          'labels/label_L0.csv labels/label_L0_retest.csv')


# ----------------------------------------------------------- reliability
def cohen_kappa(a, b):
    cats = sorted(set(a) | set(b))
    idx = {c: i for i, c in enumerate(cats)}
    n = len(a)
    m = np.zeros((len(cats), len(cats)))
    for x, y in zip(a, b):
        m[idx[x], idx[y]] += 1
    po = np.trace(m) / n
    pe = sum(m[i].sum() * m[:, i].sum() for i in range(len(cats))) / (n * n)
    return (po - pe) / (1 - pe) if pe != 1 else 1.0, po


def krippendorff_alpha(matrix):
    """Nominal alpha. matrix: list of rows, each a list of labels (None = missing)."""
    vals, pairs = [], 0
    counts = {}
    for row in matrix:
        r = [v for v in row if v is not None]
        if len(r) < 2:
            continue
        m = len(r)
        pairs += m
        for i in range(m):
            for j in range(m):
                if i != j:
                    counts[(r[i], r[j])] = counts.get((r[i], r[j]), 0) + 1 / (m - 1)
        vals.extend(r)
    if not vals:
        return float('nan')
    cats = sorted(set(vals))
    n = len(vals)
    do = sum(v for (a, b), v in counts.items() if a != b) / pairs
    marg = {c: vals.count(c) for c in cats}
    de = sum(marg[a] * marg[b] for a in cats for b in cats if a != b) / (n * (n - 1))
    return 1 - do / de if de else float('nan')


def agree(pa, pb):
    a = pd.read_csv(pa).set_index('uid').label.astype(str).str.upper()
    b = pd.read_csv(pb).set_index('uid').label.astype(str).str.upper()
    common = a.index.intersection(b.index)
    a, b = a.loc[common], b.loc[common]
    k, po = cohen_kappa(list(a), list(b))
    alpha = krippendorff_alpha([[x, y] for x, y in zip(a, b)])
    print(f'overlapping items: {len(common)}')
    print(f'raw agreement     : {po:.3f}')
    print(f"Cohen's kappa     : {k:.3f}")
    print(f"Krippendorff alpha: {alpha:.3f}")
    print(f'\nreference: Rani et al. (2020) reported alpha = 0.47')
    if alpha >= 0.67:
        print('  >= 0.67 — acceptable for drawing conclusions.')
    elif alpha >= 0.47:
        print('  beats Rani et al., but below the 0.67 convention. '
              'Report it plainly and discuss which categories disagree.')
    else:
        print('  below Rani et al. The guideline needs revising BEFORE '
              'more labelling, and the revision must be versioned.')
    dis = pd.DataFrame({'a': a, 'b': b})
    dis = dis[dis.a != dis.b]
    if len(dis):
        print(f'\ndisagreements ({len(dis)}):')
        print(dis.groupby(['a', 'b']).size().to_string())


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cmd = sys.argv[1]
    if cmd == 'l0':
        make_l0(sys.argv[2])
    elif cmd == 'lock':
        lock(sys.argv[2])
    elif cmd == 'l1':
        make_l1(sys.argv[2])
    elif cmd == 'retest':
        make_retest(sys.argv[2])
    elif cmd == 'agree':
        agree(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
